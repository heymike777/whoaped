import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// One-time snapshot of public Kolscan profiles. Do not run this from the API or
// add these addresses to the live wallet subscription set.
const source = 'https://kolscan.io/leaderboard';
const response = await fetch(source, { headers: { 'User-Agent': 'WhoAped-Discovery/1.0' } });
if (!response.ok) throw new Error(`Kolscan returned ${response.status}`);
const html = await response.text();
const pattern = /\\"wallet_address\\":\\"([1-9A-HJ-NP-Za-km-z]{32,44})\\",\\"name\\":\\"([^\\"]*)\\",(?:\\"pfp\\":(?:null|\\"[^\\"]*\\"),)?\\"telegram\\":(null|\\"[^\\"]*\\"),\\"twitter\\":(null|\\"[^\\"]*\\")/g;
const profiles = new Map();
const parseLink = value => value === 'null' ? null : value.slice(2, -2);
for (const match of html.matchAll(pattern)) {
  const [, address, name, telegramRaw, twitterRaw] = match;
  if (profiles.has(address)) continue;
  const twitter = parseLink(twitterRaw);
  const telegram = parseLink(telegramRaw);
  profiles.set(address, {
    address,
    name: name.trim() || `${address.slice(0, 6)}…${address.slice(-4)}`,
    twitter: twitter?.startsWith('https://x.com/') || twitter?.startsWith('https://twitter.com/') ? twitter : null,
    telegram: telegram?.startsWith('https://t.me/') ? telegram : null,
  });
}
if (profiles.size < 100) throw new Error(`Only ${profiles.size} profiles parsed; refusing to replace snapshot`);
const snapshot = {
  source,
  importedAt: new Date().toISOString(),
  profiles: [...profiles.values()].sort((a, b) => a.name.localeCompare(b.name)),
};
const target = fileURLToPath(new URL('../src/data/kolscan-profiles.ts', import.meta.url));
await writeFile(target, `// Generated by scripts/import-kolscan.mjs. Do not edit by hand.\nexport const kolscanSnapshot = ${JSON.stringify(snapshot, null, 2)} as const;\n`);
console.log(`Imported ${profiles.size} profiles from ${source}`);
