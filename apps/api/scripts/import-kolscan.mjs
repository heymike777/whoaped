import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { fetchKolscanProfiles, KOLSCAN_SOURCE_URL } from '../src/services/kolscan-source.ts';

// One-time snapshot of public Kolscan profiles. Do not run this from the API or
// add these addresses to the live wallet subscription set.
const profiles = await fetchKolscanProfiles();
const snapshot = {
  source: KOLSCAN_SOURCE_URL,
  importedAt: new Date().toISOString(),
  profiles: profiles.sort((a, b) => a.name.localeCompare(b.name)),
};
const target = fileURLToPath(new URL('../src/data/kolscan-profiles.ts', import.meta.url));
await writeFile(target, `// Generated by scripts/import-kolscan.mjs. Do not edit by hand.\nexport const kolscanSnapshot = ${JSON.stringify(snapshot, null, 2)} as const;\n`);
console.log(`Imported ${profiles.length} profiles from ${KOLSCAN_SOURCE_URL}`);
